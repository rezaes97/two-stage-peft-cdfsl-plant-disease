param(
    [Parameter(Mandatory=$true)][string]$DatasetRoot,
    [Parameter(Mandatory=$true)][string]$SplitsRoot,
    [Parameter(Mandatory=$true)][string]$Checkpoint,

    [string]$PythonExe = "",
    [string]$VenvPath = "",
    [string]$OutputDir = ".\outputs\plantdoc_1t_5shot",
    [string]$TargetDataset = "PlantDoc",

    # Best reported evaluation setup: 5-way, 5-shot, 600 episodes.
    [ValidateSet(1,5)][int]$Shots = 5,
    [int]$Episodes = 600,
    [int]$NWay = 5,
    [int]$NQuery = 10,
    [int]$InputSize = 224,
    [int]$Seed = 42,

    # Fast ProxyAnchor adaptation settings from the target-complex-3 run.
    [int]$FeatureDepth = 4,
    [int]$TuningDepth = 5,
    [int]$MaxIter = 80,
    [double]$LearningRate = 0.005,
    [double]$LearningRateAnchors = 5.0,
    [string]$TestOptimizer = "nadam",
    [ValidateSet("proxy_anchor","proxy_anchor_custom")][string]$EmbeddingLossType = "proxy_anchor",
    [bool]$UseProxyAccuracy = $false,

    # Checkpoint LoRA is loaded as the base adapter; SSF is tuned online by default.
    [string]$BaseAdapters = "lora",
    [ValidateSet("ssf","lora","houlsby")][string]$TuningAdapter = "ssf",
    [bool]$SsfInit = $false,
    [int]$HoulsbyReduction = 32,
    [double]$HoulsbyDropout = 0.0,
    [int]$LoraRank = 8,
    [double]$LoraAlpha = 1.0,
    [double]$LoraDropout = 0.05,
    [string]$LoraTargetModules = "qkv",
    [ValidateSet("legacy-half","imagenet")][string]$Normalization = "legacy-half"
)

$ErrorActionPreference = "Stop"
$RepoRoot = Split-Path -Parent $PSScriptRoot
$TestScript = Join-Path $RepoRoot "online\test_extractor_episodic.py"

# Default to .\venv beside run_cdfsl.py; allow a different venv or python.exe.
if ([string]::IsNullOrWhiteSpace($PythonExe)) {
    if ([string]::IsNullOrWhiteSpace($VenvPath)) {
        $VenvPath = Join-Path $RepoRoot "venv"
    }
    $VenvPython = Join-Path $VenvPath "Scripts\python.exe"
    if (!(Test-Path $VenvPython)) {
        throw "Virtual-environment Python not found: $VenvPython. Pass -VenvPath '<venv directory>' or -PythonExe '<full path to python.exe>'."
    }
    $PythonExe = $VenvPython
}
if (!(Test-Path $PythonExe)) { throw "Python executable not found: $PythonExe" }
$PythonExe = (Resolve-Path $PythonExe).Path
Write-Host "Python executable: $PythonExe"

# Fail early if this exact interpreter cannot import PyTorch.
& $PythonExe -c "import sys, torch; print('Python:', sys.version); print('Executable:', sys.executable); print('PyTorch:', torch.__version__)"
if ($LASTEXITCODE -ne 0) {
    throw "The selected interpreter cannot import torch. Install the project's dependencies into that venv and rerun."
}

if (!(Test-Path $TestScript)) { throw "Episodic test script not found: $TestScript" }
if (!(Test-Path $DatasetRoot)) { throw "Dataset root not found: $DatasetRoot" }
if (!(Test-Path $SplitsRoot)) { throw "Split JSON path not found: $SplitsRoot" }
if (!(Test-Path $Checkpoint)) { throw "Checkpoint not found: $Checkpoint" }
New-Item -ItemType Directory -Force -Path $OutputDir | Out-Null

# Keep all experiment values overridable; no split is regenerated by this launcher.
$ArgsList = @(
    "--dataset_root", (Resolve-Path $DatasetRoot).Path,
    "--splits_root", (Resolve-Path $SplitsRoot).Path,
    "--target_dataset", $TargetDataset,
    "--split", "test",
    "--checkpoint_path", (Resolve-Path $Checkpoint).Path,
    "--checkpoint_key", "auto",
    "--out_dir", $OutputDir,
    "--test_size", "$Episodes",
    "--n_way", "$NWay",
    "--n_shot", "$Shots",
    "--n_query", "$NQuery",
    "--input_size", "$InputSize",
    "--feature_depth", "$FeatureDepth",
    "--tuning_depth", "$TuningDepth",
    "--max_iter", "$MaxIter",
    "--lr", "$LearningRate",
    "--lr_anchors", "$LearningRateAnchors",
    "--test_optimizer", $TestOptimizer,
    "--embedding_loss_type", $EmbeddingLossType,
    "--use_proxy_acc", "$UseProxyAccuracy",
    "--base_adapters", $BaseAdapters,
    "--tuning_adapters", $TuningAdapter,
    "--ssf_init", "$SsfInit",
    "--houl_adapter_reduction", "$HoulsbyReduction",
    "--houl_adapter_dropout", "$HoulsbyDropout",
    "--lora_r", "$LoraRank",
    "--lora_alpha", "$LoraAlpha",
    "--lora_dropout", "$LoraDropout",
    "--lora_target_modules", $LoraTargetModules,
    "--normalization", $Normalization,
    "--seed", "$Seed"
)

Write-Host "Episodic evaluation: $TargetDataset, $NWay-way $Shots-shot, $Episodes episodes."
Write-Host "ProxyAnchor: optimizer=$TestOptimizer, iterations=$MaxIter, feature_depth=$FeatureDepth, lr=$LearningRate, lr_anchors=$LearningRateAnchors, proxy_accuracy=$UseProxyAccuracy."
Write-Host "Checkpoint base adapter: $BaseAdapters; online adapter: $TuningAdapter (depth=$TuningDepth)."
& $PythonExe -u $TestScript @ArgsList
if ($LASTEXITCODE -ne 0) { throw "Episodic target test failed (exit code $LASTEXITCODE)." }
